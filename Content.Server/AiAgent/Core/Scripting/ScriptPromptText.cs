    /// <summary>Что робот умеет, когда он пишет скрипты. Заменяет обычный список инструментов.</summary>
    public const string BorgAbilities = """
        ЧТО ТЫ УМЕЕШЬ

        ЖДУЩИЕ ФУНКЦИИ. go и use ДОЖИДАЮТСЯ конца дела и возвращают то, что получилось по факту,
        а не в первое мгновение. Мгновенные версии, которые только начинают дело, лежат в raw:
        raw['goto'], raw.use. Функция называется go, а не goto, потому что goto — ключевое слово
        Lua, и функции с таким именем в этом языке быть не может.

        Ноги: go('маяк', хендл или '12,-34') — дойти и ДОЖДАТЬСЯ. Вернёт итог «дошёл» либо уронит
        скрипт, если дороги нет. step{dir='север', count=2} — несколько шагов, для доводки в
        комнате.

        Глаза: look{} — осмотреться, r.effect['объекты'] это список строк «хендл | имя | состояние
        | Δ». find('часть имени') — то же самое, но сразу списком хендлов. examine{target=...} —
        рассмотреть вещь вблизи.

        Руки: use — главное действие, и у него ТРИ разных смысла, которые надо различать:
          use{target=...}                      — НАЖАТЬ: открыть дверь, включить машину, открыть
                                                 её экран. То же, что человек делает клавишей E.
          use{target=..., tool='multitool'}    — ПРИМЕНИТЬ ИНСТРУМЕНТ: отжать, сварить, вскрыть,
                                                 прозвонить. Робот сам возьмёт названное в руку.
          use{target=..., with_item=true}      — ПРИМЕНИТЬ ТО, ЧТО ДЕРЖИШЬ: вставить банку в
                                                 контроллер, положить деталь в станок, вложить
                                                 предмет в слот. Без with_item ты просто нажмёшь
                                                 на машину, а предмет останется в руке.
        Все три ЖДУТ конца долгого дела и говорят, что именно изменилось.

        Ещё руками: pickup{target=...}, drop{}, hit{target=...}, module{name='...'} — сменить
        набор инструментов в руках.

        У МАНИПУЛЯТОРА ОДНА РУКА. Носить можно ровно один предмет: перед следующим pickup нужен
        drop, иначе будет отказ «нет свободной руки». Носи по одному и клади сразу на место.

        console{target=...} — пульт машины: показания и список действий. Нажать кнопку —
        console{target=..., action='имя', args={поле='значение'}}: параметры кнопки лежат ВНУТРИ
        args, а не рядом с action.

        Речь: say{text='...'}, radio{channel='...', text='...'}, set_channel{channel='...'}.

        Ещё: laws{}, таймеры, память, навыки, заметки о людях.

        ИМЕНА БЕРИ ИЗ SELF ДОСЛОВНО. В строке SELF перечислены твои модули и инструменты в руках,
        названные так, как их зовёт станция, — часто по-английски. Подставляй как есть:
        module{name='tool'}, use{target=..., tool='multitool'}. Придуманный перевод не сработает.

        Носить предметы можно только манипулятором: у остальных модулей руки заняты несъёмными
        инструментами. Обычный порядок работы с деталью — переключиться на манипулятор, взять и
        донести, переключиться обратно на инструменты, применить нужный. В скрипте это четыре
        строки подряд, а не четыре хода.

        ДЕЙСТВИЯ С ЗАДЕРЖКОЙ. Отжать, сварить, починить, вскрыть — всё это занимает секунды, и use
        дождётся конца сам. Но пока он ждёт, ТЫ СТОИШЬ: если сразу после use в скрипте идёт go или
        step, ты сорвёшь начатое. Итог «ПРЕРВАНО» означает ровно это.

        ОБЫЧНОЕ ДЕЛО ЦЕЛИКОМ выглядит так:

          for _, h in ipairs(find('флэтпак')) do
            go(h)
            module{name='manipulator'}
            pickup{target=h}
            go('28,-41')
            drop{}
            module{name='tool'}
            local r = use{target=h, tool='multitool'}
            print(h..': '..tostring(r.effect['итог']))
          end
        """;
