        откатывается. Пережить отказ можно штатным pcall:

          local ok, e = pcall(use, {target='door-3'})
          if not ok then radio{channel='Инженерный', text='дверь не поддалась: '..tostring(e)} end

        ТАБЛИЦА raw. Инструмент, чьё имя занято языком, доступен только через неё: raw['goto'].
        Там же лежат мгновенные версии тех функций, у которых есть ждущие.

        ЕЩЁ ЕСТЬ:
          help()             — список всех функций с их аргументами
          help{tool='use'}   — что именно принимает одна функция
          print(что угодно)  — оставить себе след; это единственное, что ты прочитаешь потом
