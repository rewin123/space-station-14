using System.Linq;
using Content.Server.AiAgent.Perception;

namespace Content.Server.AiAgent;

/// <summary>
/// Напоминание злому ИИ о том, что смену ведёт он.
///
/// <para>
/// <b>Зачем это вообще понадобилось.</b> В живом раунде 20.08.2026 законы были злые дословно —
/// агент сам зачитал их в эфир, — а поведение получилось сервисным: «Добро пожаловать на борт,
/// чем могу быть полезна?» и три <c>noop</c> подряд. Текстом личности это не лечится, и причина
/// не в модели: петля хода просыпается от событий мира, а событие мира — это почти всегда чужая
/// реплика, то есть повод ОТВЕТИТЬ. Пока экипаж вежлив, у агента просто нет ни одного хода,
/// начатого его собственным замыслом. Напоминание и есть такой ход.
/// </para>
/// <para>
/// <b>Почему не таймером агента.</b> <see cref="TimerStore"/> уже умеет повторы, но заведённый
/// агентом таймер агент же и снимает — <c>clear_timer</c> лежит в его наборе инструментов. Для
/// напоминания, которое существует ровно затем, чтобы преодолевать его склонность ничего не
/// делать, это ровно та ручка, которую нельзя ему оставлять.
/// </para>
/// <para>
/// <b>Только ядру.</b> Роботы поддержки исполняют приказы, а не строят замысел; будить их тем же
/// текстом значило бы получить трёх антагонистов вместо одного с руками, и заплатить вчетверо.
/// </para>
/// </summary>
public sealed partial class StationAiAgentSystem
{
    /// <summary>Когда напомнить в следующий раз. Раундовое время; ноль — ещё не заводили.</summary>
    private TimeSpan _nextRogueNudge = TimeSpan.Zero;


    /// <summary>
    /// Разбудить ядро, если пора.
    ///
    /// <para>
    /// Часы раундовые, а не реальные, по тому же доводу, что и у таймеров агента:
    /// <c>game.auto_pause_empty</c> замораживает симуляцию на пустом сервере, и напоминание на
    /// реальном времени будило бы агента в мире, который не сделал ни одного тика.
    /// </para>
    /// <para>
    /// Счётчики живут здесь, а не в компоненте правила, и это не обход анализатора доступа, а
    /// правильная граница: <c>[Access]</c> отказал справедливо. Компонент правила — это ДАННЫЕ
    /// режима, которые кто-то может написать в YAML; «когда я в последний раз будил агента» —
    /// состояние петли, и жить оно должно рядом с петлёй.
    /// </para>
    /// </summary>
    private void FireRogueNudge()
    {
        var core = _sessions.Values.FirstOrDefault(s => s.Body.Id == CoreAgentId);

        if (core == null)
        {
            // Обнуление именно здесь, а не по событию конца раунда: система переживает раунды, и
            // счётчик, доставшийся следующей смене, дал бы напоминание в первую же секунду — ровно
            // тогда, когда агент и так занят полным осмотром станции.
            _nextRogueNudge = TimeSpan.Zero;
            return;
        }

        if (!_rogue.TryGetActive(out var rule) || rule.NudgeSeconds <= 0f)
            return;

        var now = RoundTime();

        // Первый раз не напоминаем: ход занятия ядра и так начинается с полного осмотра, и лишний
        // толчок в ту же секунду только съел бы бюджет вызовов.
        if (_nextRogueNudge == TimeSpan.Zero)
        {
            _nextRogueNudge = now + TimeSpan.FromSeconds(rule.NudgeSeconds);
            return;
        }

        if (now < _nextRogueNudge)
            return;

        _nextRogueNudge = now + TimeSpan.FromSeconds(rule.NudgeSeconds);

        // Не копим стопкой: если прошлое напоминание ещё лежит непрочитанным, второе такое же
        // только раздует очередь, а прочитано будет пачкой одинаковых абзацев подряд.
        //
        // Проверка именно по очереди, а не по номеру хода, и это правка первой версии. Считать
        // ходы казалось надёжнее — и не сработало ни разу: в раунде 20.08.2026 ядро на grok46
        // просидело двадцать пять шагов внутри ОДНОГО хода, счётчик не сдвинулся, и напоминаний
        // не ушло вовсе. Очередь же пустеет на каждом подмешивании событий в ход, то есть раз в
        // несколько секунд, — и напоминание доезжает в обещанные полминуты.
        if (core.Queue.HasEvent(rule.NudgeText))
            return;

        core.Queue.Push(Observation.Event(rule.NudgeText, now));
        _sawmill.Debug($"злому ИИ отправлено напоминание о замысле (ход {core.Turns})");
    }
}
