#!/usr/bin/env bash
#
# ПРИМЕР: llama-server под агента SS14.
#
# Не «оптимальные настройки» — их не бывает без вашего железа и вашей модели. Это разбор флагов,
# которые агент действительно замечает, и объяснение, почему каждый стоит так, а не иначе.
# Скопируйте, поправьте пути и числа.
#
#   cp Tools/examples/llamacpp/llama-server.sh ~/llama-agent.sh && chmod +x ~/llama-agent.sh
#
# Парный файл настроек игры — 10-endpoints.yml в этом же каталоге.

set -euo pipefail

MODEL="${MODEL:-$HOME/models/your-model-Q4_K_M.gguf}"
PORT="${PORT:-8080}"

# ---------------------------------------------------------------------------------------------
# ИМЯ МОДЕЛИ
#
# Без --alias llama-server отдаёт в /v1/models имя файла весов. Игре всё равно, чем модель
# называется, но НЕ всё равно, совпадает ли имя с полем `model` в профиле: несовпадение — это
# 404 на каждом ходу, и `aiagent llm probe` ловит его первым делом. Задать явно проще, чем
# помнить, как назывался файл.
ALIAS="${ALIAS:-local-model}"

# ---------------------------------------------------------------------------------------------
# КОНТЕКСТ
#
# Число обязано совпадать с ctxLimit в профиле, и агент это проверяет: ctxProbe: Props заставляет
# его спросить настоящий n_ctx через /props. Перезапустив сервер с другим -c и забыв про профиль,
# вы получите молчаливое расхождение — агент будет сворачиваться по старому порогу.
#
# И помните про --parallel ниже: контекст ДЕЛИТСЯ между слотами.
CTX="${CTX:-131072}"

# ---------------------------------------------------------------------------------------------
# СЛОТЫ
#
# Один слот на агента. У форка их может быть до ai.max_agents (по умолчанию 8: ядро и семь тел),
# и на ОДНОМ слоте они вытесняют префикс-кэш друг друга — каждый ход становится полным prefill.
# Это не «медленнее на проценты», это разница в разы.
#
# Цена: n_ctx на слот равен CTX/PARALLEL. Три слота по 43k из 131k — рабочая раскладка; восемь
# слотов из тех же 131k дадут по 16k, и агент будет сворачиваться каждые несколько ходов.
# Считайте от числа тел, которые реально играют, а не от максимума.
PARALLEL="${PARALLEL:-3}"

exec llama-server \
  --model "$MODEL" \
  --alias "$ALIAS" \
  --host 127.0.0.1 \
  --port "$PORT" \
  --ctx-size "$CTX" \
  --parallel "$PARALLEL" \
  \
  `# Кэш промпта между запросами. Профиль шлёт cache_prompt: true (диалект LlamaCpp), но без` \
  `# этого флага серверу нечего кэшировать. Промпт агента — это десятки тысяч токенов системной` \
  `# части, неизменной весь раунд; без кэша каждый ход платит за неё заново.` \
  --cache-reuse 256 \
  \
  `# ВЫЗОВ ИНСТРУМЕНТОВ. Без него агент не может НИЧЕГО: весь его мир — это функции, а текст без` \
  `# вызова в игре выглядит как молчащий ИИ, а не как ошибка. Если модель не умеет tool calling,` \
  `# она не подходит, и заметить это надо здесь, а не в раунде.` \
  --jinja \
  \
  `# УРОВЕНЬ РАЗМЫШЛЕНИЯ ЗАДАЁТСЯ ЗДЕСЬ, И ТОЛЬКО ЗДЕСЬ.` \
  `#` \
  `# Поле reasoning_effort в теле запроса llama-server принимает и молча игнорирует — поэтому в` \
  `# профиле оно оставлено пустым. Раскомментируйте строку ниже для рассуждающей модели; для` \
  `# нерассуждающей флаг не нужен и на некоторых шаблонах ломает разбор.` \
  `#` \
  `# Смысл low, а не high: у агента ход стоит секунд, а не качества. Замер на Grok 4.6 дал` \
  `# 233-243 токена размышления и 4-7 секунд против 653-858 и 16-19 — в игре разница между` \
  `# «ИИ ответил» и «ИИ молчит».` \
  `# --chat-template-kwargs '{"reasoning_effort":"low"}' \` \
  \
  `# Метрики на /metrics: глубина очереди, попадания в кэш, токены в секунду. Дешёвый флаг,` \
  `# который однажды ответит на вопрос «модель тормозит или агент?».` \
  --metrics \
  \
  `# Выгрузка на видеокарту. -1 — все слои; уменьшайте, если не влезает.` \
  --n-gpu-layers -1 \
  \
  `# Сэмплеры. Профиль шлёт свои значения в каждом запросе (top_k, min_p — расширения llama.cpp,` \
  `# легальные при dialect: LlamaCpp), так что здешние — только умолчание для запросов без них.` \
  --temp 0.7 \
  --top-p 0.95 \
  --min-p 0.05

# ---------------------------------------------------------------------------------------------
# ПРОВЕРКА, ПРЕЖДЕ ЧЕМ ИДТИ В ИГРУ
#
#   curl -s --noproxy '*' 127.0.0.1:8080/v1/models | jq -r '.data[].id'
#       ← должно напечатать ровно то, что стоит в поле `model` профиля.
#
#   curl -s --noproxy '*' 127.0.0.1:8080/props | jq '.default_generation_settings.n_ctx'
#       ← настоящий n_ctx НА СЛОТ (CTX/PARALLEL), и именно его увидит агент через ctxProbe: Props.
#         Сверьте с compactHigh: порог свёртки, равный окну или больше, не сработает никогда.
#
#   --noproxy '*' здесь не для красоты: при глобальном HTTP_PROXY запрос на loopback уходит в
#   прокси и зависает. Ровно то же случится с игровым сервером, если в профиле не стоит
#   proxy: None.
#
# И уже из консоли сервера — то же самое, но глазами игры:
#
#   aiagent llm probe llamacpp
