#!/usr/bin/env python3
"""Запустить агента pi на одной категории внутренней вики.

Один запуск — одна категория и новый агент без памяти о предыдущих: у местной модели 262k
контекста, и категория целиком в них помещается, а вот шестнадцать категорий подряд одним
сеансом — нет. Ничего общего между запусками нет и не нужно: пересечения тем ловит линтер.

    python3 Tools/wiki/run.py питание [--dry]

--dry печатает промпт и выходит, не тратя полчаса машинного времени на проверку опечатки.
"""

import os
import re
import subprocess
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).parent))
import manifest  # noqa: E402

MODEL = "qwen3.8-27b-q8"
PROVIDER = "llama-swap"

PROMPT = """Ты пишешь справочник для ИИ-агента, который играет роль Станционного ИИ в Space
Station 14 на живом сервере с живыми игроками. Агент говорит по-русски, читает справочник во время
смены и по нему помогает экипажу отыгрывать их роли: объясняет, что и в каком порядке делать,
называет точные числа и названия.

Сейчас справочник слишком поверхностный. По нему нельзя провести человека через роль целиком:
общие слова есть, а порядка действий, цифр и названий нет. Твоя работа — вернуть эту глубину из
внутренней вики игры, которая лежит в этом же репозитории.

КАТЕГОРИЯ: {title}

ИСТОЧНИК — прочитай КАЖДЫЙ из этих файлов целиком, это внутренняя вика игры:
{sources}

УЖЕ НАПИСАННОЕ — прочитай КАЖДЫЙ, чтобы не повторять и держать тот же тон:
{existing}

ЗАДАЧА
Напиши в каталог wiki_skills/ новые статьи, которые дают то, чего в уже написанном нет:
пошаговые процедуры, точные числа, формулы, названия предметов и машин, пороги, последовательности
сборки, списки. Держись источника почти дословно: если в вике написано «объёмный насос настраивают
на 200/N литров в секунду», эта формула обязана оказаться в статье. Каждое число, каждое имя
собственное, каждый порядок шагов из источника — ценность. Ради краткости их терять нельзя, именно
на этом справочник и испортился в прошлый раз.

Пиши по-русски. Английские названия машин, предметов и газов давай так: русское название, а рядом
в скобках английское, как оно называется в игре — например «теплообменник (heat exchanger)».
Игрок видит английский интерфейс, и без оригинального имени совет бесполезен.

ФОРМАТ — ровно такой, парсер строгий. Один файл — одна статья, wiki_skills/<имя>.md:

# <имя-статьи>
когда: <когда её открывать, НЕ ДЛИННЕЕ 60 СИМВОЛОВ>
<тело статьи, НЕ ДЛИННЕЕ 4800 СИМВОЛОВ>

Имя файла и имя в заголовке `#` обязаны совпадать. Имя — строчными буквами, слова через дефис,
начинается с «{prefix}». Ровно два слова: префикс и одно существительное по теме, например
«{prefix}пример». Не давай имени, которое есть другое имя плюс уточняющее слово: если есть
«{prefix}котёл», то «{prefix}котёл-запуск» — запрещённое имя, парсер считает их одной статьёй.

Ссылка на соседнюю статью пишется как [[имя-статьи]] прямо в тексте. Ссылайся только на статьи,
которые точно существуют: на те, что перечислены выше как уже написанные, и на те, что пишешь
сейчас сам. Ссылка в никуда — ошибка.

ЧЕГО ДЕЛАТЬ НЕЛЬЗЯ
Не переписывай и не трогай файлы в skill_start/ — они уже вычитаны человеком. Пиши только в
wiki_skills/.
Не описывай инструменты агента и не пиши вызовов вида look {{...}}, inspect {{...}},
device_action {{...}}. Этот слой уже есть в skill_start/, и выдуманный вызов стоит агенту хода.
Здесь только знание об игре: как она устроена и что делает человек руками.
Не выдумывай. Если чего-то в источнике нет — этого нет. Лучше короткая статья, чем правдоподобная
выдумка: агент говорит это живым людям вслух.
Не пересказывай своими словами то, что уже написано в skill_start/. Твоя статья ценна ровно тем,
чего там нет.

ПОРЯДОК РАБОТЫ
1. Прочитай все файлы источника и все уже написанные статьи.
2. Составь список того, что есть в источнике и отсутствует в уже написанном.
3. Раздели этот список на статьи по 3500-4800 символов. Ориентир: {target} статей.
4. Пиши статьи по одной, инструментом write, полностью. Не оставляй заготовок и не пиши
   «продолжение следует» — недописанная статья хуже отсутствующей.
5. Закончив, перечисли одной строкой имена написанных статей.

ПРО ДЛИНУ. Потолок 4800 символов — это цель, а не опасность. Статья на 1500 символов означает,
что ты пересказал источник вместо того, чтобы его перенести: вернись к ней и добавь то, что
выбросил. Ни один файл из списка источника не должен остаться неотражённым ни в одной статье —
пройди список в конце и проверь себя по нему поимённо.
"""


def prose_size(paths):
    total = 0
    for p in paths:
        try:
            t = Path(p).read_text(encoding="utf-8", errors="replace")
        except OSError:
            continue
        total += len(re.sub(r"\[/?[^\]]*\]", "", re.sub(r"<[^>]*>", "", t)))
    return total


def main():
    if len(sys.argv) < 2:
        raise SystemExit(__doc__)

    key = sys.argv[1]
    cat = manifest.category(key)
    _, prefix, _, title = cat

    sources = manifest.files_of(cat)
    existing = sorted(Path("skill_start").glob(f"{prefix}*.md")) if prefix else []

    # Ориентир по объёму источника, а не по числу существующих статей: сколько в вике текста,
    # столько его и надо перенести. Делитель меньше рабочей длины статьи: перевод на русский с
    # английским названием в скобках рядом длиннее оригинала примерно на четверть.
    target = max(2, min(20, prose_size(sources) // 3000))

    prompt = PROMPT.format(
        title=title,
        prefix=prefix or "<префикс по теме>",
        sources="\n".join("  " + s for s in sources),
        existing="\n".join("  " + str(e) for e in existing) or "  (по этой теме статей ещё нет)",
        target=target,
    )

    if "--dry" in sys.argv:
        print(prompt)
        return 0

    out = Path("wiki_skills")
    out.mkdir(exist_ok=True)
    log = out / f".log-{key}.txt"

    print(f"=== {key}: {len(sources)} файлов источника, {prose_size(sources)} симв прозы, "
          f"ориентир {target} статей", flush=True)

    # Локальная модель иногда возвращает пустой ответ, ничего не написав и не сообщив об ошибке:
    # ноль байт на stdout, ноль на stderr, код возврата 0. На категории «мед» так ушло 18 минут
    # впустую, и заметить это можно было только по отсутствию файлов. Поэтому успех меряется тем,
    # что осталось на диске, а не тем, что сказал процесс.
    before = {f.name for f in out.glob(f"{prefix}*.md")} if prefix else set()

    for attempt in (1, 2):
        proc = subprocess.run(
            ["pi", "-p", "--provider", PROVIDER, "--model", MODEL, "--no-session",
             "-t", "read,write", "--thinking", "medium", prompt],
            capture_output=True, text=True, cwd=os.getcwd())

        log.write_text(f"--- попытка {attempt}, код {proc.returncode} ---\n"
                       + proc.stdout + "\n--- stderr ---\n" + proc.stderr, encoding="utf-8")
        print(proc.stdout[-3000:])

        written = {f.name for f in out.glob(f"{prefix}*.md")} - before if prefix else set()
        if written:
            return 0

        print(f"попытка {attempt}: pi не написал ни одной статьи (код {proc.returncode}, "
              f"{len(proc.stdout)} байт ответа)", file=sys.stderr, flush=True)

    return 1


if __name__ == "__main__":
    sys.exit(main())
